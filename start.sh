#!/usr/bin/env bash
# Запуск НАРЕЗАТОРА так, чтобы он не умирал.
#
#   ./start.sh           — обычный запуск, порт 4173
#   PORT=8080 ./start.sh — другой порт
#
# Скрипт сам доставит зависимости, если их нет, и поднимет сервер заново,
# если процесс упадёт. Диск (data/) он, разумеется, не спасает — если
# песочницу выключили, временные файлы теряются, и загрузку надо повторить.

cd "$(dirname "$0")" || exit 1
PORT="${PORT:-4173}"

# зависимости могли не пережить перезапуск окружения
if [ ! -d node_modules/express ]; then
  echo "→ ставлю зависимости"
  npm install --no-audit --no-fund || { echo "не удалось поставить зависимости"; exit 1; }
fi

# сервер уже слушает порт — второй не нужен
if curl -fsS -o /dev/null "http://127.0.0.1:${PORT}/" 2>/dev/null; then
  echo "→ НАРЕЗАТОР уже работает на http://127.0.0.1:${PORT}"
  exit 0
fi

echo "→ НАРЕЗАТОР на http://127.0.0.1:${PORT} · остановить: Ctrl+C"

# пока скрипт жив — сервер тоже. Упал — поднимем через секунду.
while true; do
  PORT="$PORT" node server.js
  code=$?
  [ "$code" = 130 ] && break          # Ctrl+C
  echo "→ сервер упал (код $code), поднимаю заново"
  sleep 1
done
